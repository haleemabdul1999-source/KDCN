/**
 * Generates docs/API-ROUTES.md from controller metadata (routes, HTTP methods and access rules),
 * so the route reference cannot drift from the code. Usage: node dist/scripts/api-docs.js
 */
import 'reflect-metadata';
import { RequestMethod } from '@nestjs/common';
import { METHOD_METADATA, PATH_METADATA } from '@nestjs/common/constants';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { IS_PUBLIC, SKIP_CSRF, STAFF_ROLES } from '../common/auth/decorators';

process.env.DATABASE_URL ??= 'postgresql://unused/unused';
process.env.DATA_ENCRYPTION_KEY ??= Buffer.alloc(32).toString('base64');
process.env.APP_SECRET ??= 'x'.repeat(40);

// eslint-disable-next-line @typescript-eslint/no-require-imports
const { AppModule } = require('../app.module');

type Ctor = new (...args: unknown[]) => unknown;
const controllers: Ctor[] = Reflect.getMetadata('controllers', AppModule) ?? [];

const join = (...parts: string[]) =>
  '/' +
  parts
    .flatMap((p) => p.split('/'))
    .filter(Boolean)
    .join('/');
const rows: { path: string; method: string; access: string; handler: string }[] = [];

for (const ctrl of controllers) {
  const base: string = Reflect.getMetadata(PATH_METADATA, ctrl) ?? '';
  const classStaff: string[] | undefined = Reflect.getMetadata(STAFF_ROLES, ctrl);
  const proto = ctrl.prototype as Record<string, unknown>;
  for (const name of Object.getOwnPropertyNames(proto)) {
    const fn = proto[name];
    if (name === 'constructor' || typeof fn !== 'function') continue;
    const path: string | undefined = Reflect.getMetadata(PATH_METADATA, fn);
    const method: RequestMethod | undefined = Reflect.getMetadata(METHOD_METADATA, fn);
    if (path === undefined || method === undefined) continue;
    const isPublic = Reflect.getMetadata(IS_PUBLIC, fn);
    const staff: string[] | undefined = Reflect.getMetadata(STAFF_ROLES, fn) ?? classStaff;
    const webhook = Reflect.getMetadata(SKIP_CSRF, fn);
    const access = webhook
      ? 'Public (HMAC-signed webhook)'
      : isPublic
        ? 'Public'
        : staff
          ? `Staff + MFA${staff.length ? `: ${staff.join(', ')}` : ' (any role)'} (SUPER_ADMIN always)`
          : base.startsWith('merchant') || path.includes('merchant/')
            ? 'Signed in + merchant membership'
            : base.startsWith('operator')
              ? 'Signed in + market operator'
              : 'Signed in';
    rows.push({
      path: join('api', base, path),
      method: RequestMethod[method],
      access,
      handler: `${ctrl.name}.${name}`,
    });
  }
}

rows.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
const out = [
  '# API route reference (generated)',
  '',
  'Generated by `node apps/api/dist/scripts/api-docs.js` from controller metadata. Do not edit by hand.',
  'See [API.md](API.md) for conventions (auth, CSRF, errors, idempotency, pagination).',
  '',
  `${rows.length} routes.`,
  '',
  '| Method | Path | Access | Handler |',
  '| --- | --- | --- | --- |',
  ...rows.map((r) => `| ${r.method} | \`${r.path}\` | ${r.access} | ${r.handler} |`),
  '',
].join('\n');
const target = resolve(__dirname, '../../../../docs/API-ROUTES.md');
writeFileSync(target, out);
console.log(`wrote ${rows.length} routes to ${target}`);
